public class PrettyPrinting {
    public static void main(String[] args) {
        float a  = 123.4567f;
        System.out.printf("formated value is %.2f" , a);
        System.out.println();
        System.out.printf("pie %.3f", Math.PI);//% is the placeholder
        System.out.println();
        System.out.printf("hell my name %s and i am student of %s","vishal","b.tech");
    }
}
